export type ISODateString = string;

export type SearchEngineId = string;

export interface SearchEngine {
  id: SearchEngineId;
  name: string;
  /** URL template containing %s, or a plain URL with a q/query parameter. */
  template: string;
  colour: string;
  builtin?: boolean;
}

export interface SearchHistoryEntry {
  query: string;
  at: number;
}

export type ShortcutIcon =
  | { type: 'favicon' }
  | { type: 'text'; value: string }
  | { type: 'url'; value: string };

export interface Shortcut {
  id: string;
  label: string;
  url: string;
  categoryId: string;
  icon: ShortcutIcon;
}

export interface ShortcutCategory {
  id: string;
  name: string;
}

export type WidgetType =
  | 'clock'
  | 'weather'
  | 'calendar'
  | 'notes'
  | 'todo'
  | 'rss'
  | 'news'
  | 'bookmarks'
  | 'welcome';

export interface WidgetInstance {
  id: string;
  type: WidgetType;
  collapsed: boolean;
}

export type ColumnCount = 1 | 2 | 3 | 4;

export interface LayoutSettings {
  columns: ColumnCount;
  gap: number;
  positions: string[][];
}

export interface ThemeColours {
  bg: string;
  contentBg: string;
  widgetBg: string;
  headerTop: string;
  headerBottom: string;
  accent: string;
  text: string;
  muted: string;
  border: string;
}

export type FontPreset = 'retro' | 'modern';
export type Density = 'comfortable' | 'compact';
export type BackgroundType = 'colour' | 'gradient' | 'image';
export type SearchBarStyle = 'classic' | 'slim';

export interface BackgroundSettings {
  type: BackgroundType;
  colour: string;
  gradient: string;
  imageId?: string;
  imageUrl?: string;
  overlay: number;
}

export interface AppearanceSettings {
  themeId: string;
  colours: ThemeColours;
  fontPreset: FontPreset;
  fontSize: number;
  radius: number;
  shadows: boolean;
  density: Density;
  background: BackgroundSettings;
  searchBar: SearchBarStyle;
}

export type TickerSpeed = 'slow' | 'normal' | 'fast';

export interface NewsSettings {
  datasetUrl: string;
  categories: NewsCategory[];
  sources: string[];
  articleLimit: number;
  refreshMinutes: number;
  tickerEnabled: boolean;
  tickerSpeed: TickerSpeed;
  tickerCategories: NewsCategory[];
}

export interface SearchSettings {
  engineId: SearchEngineId;
  openInNewTab: boolean;
  saveHistory: boolean;
  customEngines: SearchEngine[];
}

export interface ShortcutSettings {
  style: 'large' | 'compact';
  showLabels: boolean;
}

export interface Settings {
  portalName: string;
  appearance: AppearanceSettings;
  layout: LayoutSettings;
  search: SearchSettings;
  news: NewsSettings;
  shortcuts: ShortcutSettings;
  showTabs: boolean;
}

export interface Note {
  id: string;
  title: string;
  body: string;
  colour: 'yellow' | 'blue' | 'green' | 'pink' | 'plain';
  updatedAt: number;
}

export interface Task {
  id: string;
  title: string;
  completed: boolean;
  dueDate?: string;
  createdAt: number;
}

export interface CalendarEvent {
  id: string;
  date: string; // YYYY-MM-DD
  title: string;
  time?: string; // HH:mm
  colour?: 'blue' | 'green' | 'pink' | 'yellow';
}

export interface BookmarkLink {
  id: string;
  label: string;
  url: string;
}

export interface BookmarkCategory {
  id: string;
  name: string;
  links: BookmarkLink[];
}

export interface WeatherLocation {
  name: string;
  latitude: number;
  longitude: number;
  country?: string;
}

export interface RssFeed {
  id: string;
  name: string;
  url: string;
  /** True for the static feed snapshots generated by the GitHub Action. */
  bundled?: boolean;
  sourceUrl?: string;
}

export interface WidgetSettingsMap {
  clock: {
    analogue: boolean;
    hour12: boolean;
    showSeconds: boolean;
    timeZone: string;
  };
  weather: {
    location: WeatherLocation;
    unit: 'celsius' | 'fahrenheit';
    forecast: boolean;
  };
  calendar: {
    weekStartsOn: 0 | 1;
  };
  notes: {
    tall: boolean;
  };
  todo: {
    showCompleted: boolean;
  };
  rss: {
    feeds: RssFeed[];
    limit: number;
    tall: boolean;
  };
  news: {
    categories: NewsCategory[];
    sources: string[];
    limit: number;
    tall: boolean;
  };
  bookmarks: {
    tall: boolean;
  };
  welcome: {
    name: string;
    message: string;
  };
}

export interface PortalData {
  version: number;
  settings: Settings;
  shortcuts: Shortcut[];
  shortcutCategories: ShortcutCategory[];
  widgets: WidgetInstance[];
  widgetSettings: {
    [K in WidgetType]?: WidgetSettingsMap[K];
  };
  notes: Note[];
  tasks: Task[];
  calendarEvents: CalendarEvent[];
  bookmarks: BookmarkCategory[];
  searchHistory: SearchHistoryEntry[];
}

export type NewsCategory = 'uk' | 'world' | 'technology' | 'business' | 'science';

export interface NewsArticle {
  id: string;
  title: string;
  source: string;
  sourceUrl?: string;
  url: string;
  publishedAt: ISODateString;
  category: NewsCategory;
  summary?: string;
}

export interface NewsDataset {
  version: number;
  updatedAt: ISODateString;
  generatedAt?: ISODateString;
  articles: NewsArticle[];
  feeds?: Array<{
    id: string;
    name: string;
    url: string;
    ok: boolean;
    error?: string;
    count: number;
  }>;
}

export interface FeedArticle {
  id: string;
  title: string;
  link: string;
  source: string;
  publishedAt: string;
  summary?: string;
}

export interface FeedSnapshot {
  version: number;
  updatedAt: string;
  feed: { title: string; url: string; link?: string };
  articles: FeedArticle[];
}

export interface WeatherForecastDay {
  date: string;
  code: number;
  high: number;
  low: number;
}

export interface WeatherData {
  temperature: number;
  apparentTemperature: number;
  humidity: number;
  windSpeed: number;
  code: number;
  isDay: boolean;
  high: number;
  low: number;
  forecast: WeatherForecastDay[];
  fetchedAt: number;
  unit: 'celsius' | 'fahrenheit';
  location: WeatherLocation;
}

export interface TodoWidgetState {
  filter: 'all' | 'active' | 'done';
}
